#!/usr/bin/env python3
"""The module surface of OpenSSL, derived from its configured public headers.

OpenSSL's public headers are generated by its Configure (`*.h.in` -> `*.h`),
so they are read as compat.openssl installs them: the include directory of
its installed package (found under the mcpp homes, or MWRAP_OPENSSL_INCLUDE).

With --clang <clang++> the headers are read by the compiler and everything
found is recorded in tools/surface.json:

  declarations   every function, type, struct/union tag, enumeration and
                 enumerator declared at file scope by a header under
                 <openssl/...>, by module: `ssl` for the libssl headers
                 (SSL_HEADERS), `crypto` for the rest. Functions declared
                 `static` (OpenSSL's `static ossl_inline`) have internal
                 linkage: a module cannot export them, so they are recorded
                 as `internal` and declared again, with the same name and
                 signature, in mcpplibs::mwrap::openssl, forwarding to the
                 header's function -- except the `ossl_check_*` helpers of the
                 type-generic stack macros, which are not API.
  macros         every macro the headers define, in one of four classes:
                 `constants` (an object-like macro whose expansion is a
                 constant expression), `calls` (a function-like or
                 object-like macro whose expansion is one call of a declared
                 function, or of another such macro, with each parameter
                 passed as one argument: declared again as a function with
                 that function's parameter and return types), and `textual`
                 (everything else, with the reason: header guards,
                 configuration switches, annotations, type-generic, variadic
                 or comma-list macros, macros that expand to declarations or
                 that use __FILE__/__LINE__ ...). Constants and calls are
                 declared under their names in mcpplibs::mwrap::openssl::macros;
                 textual macros stay macros, in <mwrap/openssl/macros.hpp>.

Whether an expansion is a constant expression, and whether a call forwards
with the derived types, is decided by the compiler: candidates are compiled
and the ones it rejects are recorded as textual with the diagnostic.

With --write the module sources are written from the record:
src/crypto.cppm, src/ssl.cppm, src/macros.cppm and src/detail/capture.hpp.
"""
import argparse
import glob
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
RECORD = ROOT / 'tools/surface.json'
VERSION = '3.5.9'
SSL_HEADERS = {'ssl.h', 'ssl2.h', 'ssl3.h', 'tls1.h', 'dtls1.h', 'srtp.h', 'sslerr.h', 'sslerr_legacy.h', 'quic.h', 'prov_ssl.h'}
# Headers that declare nothing and only reach <windows.h>-era compatibility, or that are not meant to be included alone.
SKIPPED_HEADERS = set()
DECL_KINDS = {'FunctionDecl', 'TypedefDecl', 'RecordDecl', 'CXXRecordDecl', 'EnumDecl', 'VarDecl'}
# Constants that are constant expressions on the platform the record is derived on (Linux) but not on
# another, with the condition under which the module declares them: OSSL_BAD_ASYNC_FD is Windows'
# INVALID_HANDLE_VALUE (a cast of -1 to a pointer); CRYPTO_ONCE_STATIC_INIT is Apple's
# PTHREAD_ONCE_INIT (a braced initializer).
CONDITIONAL = {
    'OSSL_BAD_ASYNC_FD': '!defined(_WIN32)',
    'CRYPTO_ONCE_STATIC_INIT': '!defined(__APPLE__)',
}


def guarded(name, line):
    condition = CONDITIONAL.get(name)
    return [f'#if {condition}', line, '#endif'] if condition else [line]


FILE_MACROS = ('OPENSSL_FILE', 'OPENSSL_LINE', 'OPENSSL_FUNC', '__FILE__', '__LINE__', 'OPENSSL_MSTR')


# ── where the headers are ────────────────────────────────────────────────────

def include_dir():
    explicit = os.environ.get('MWRAP_OPENSSL_INCLUDE')
    if explicit:
        return Path(explicit)
    homes = [ROOT / '.mcpp', Path(os.environ.get('MCPP_HOME', Path.home() / '.mcpp')), Path.home() / '.mcpp']
    for home in homes:
        for pattern in (f'**/compat-x-openssl/{VERSION}/include/openssl/opensslv.h',):
            found = sorted(glob.glob(str(home / pattern), recursive=True))
            if found:
                return Path(found[0]).parent.parent
    sys.exit('compat.openssl ' + VERSION + ' headers not found: build the package once (mcpp build) or set MWRAP_OPENSSL_INCLUDE')


def headers(include):
    return sorted(p.name for p in (include / 'openssl').glob('*.h') if p.name not in SKIPPED_HEADERS)


def module_of(header):
    return 'ssl' if header in SSL_HEADERS else 'crypto'


# ── declarations, from clang's JSON AST ──────────────────────────────────────

def ast(clang, include, names):
    with tempfile.TemporaryDirectory(prefix='openssl-surface-') as directory:
        source = Path(directory) / 'all.cpp'
        source.write_text(''.join(f'#include <openssl/{h}>\n' for h in names), encoding='utf-8')
        command = [clang, '-std=c++23', '-fsyntax-only', '-w', '-I', str(include), '-Xclang', '-skip-function-bodies',
                   '-Xclang', '-ast-dump=json', str(source)]
        return json.loads(subprocess.run(command, check=True, stdout=subprocess.PIPE, text=True).stdout)


class FileTracker:
    """Clang's JSON names a location's file only when it differs from the last location it wrote."""

    def __init__(self):
        self.last = None

    def loc(self, loc):
        if not isinstance(loc, dict):
            return None
        if 'spellingLoc' in loc or 'expansionLoc' in loc:
            self.loc(loc.get('spellingLoc'))
            return self.loc(loc.get('expansionLoc'))
        if 'file' in loc:
            self.last = loc['file']
        return self.last if loc else None

    def node(self, node):
        """The expansion file of the node's own location; every location inside it is consumed in order."""
        here = self.loc(node.get('loc'))
        rng = node.get('range') or {}
        self.loc(rng.get('begin'))
        self.loc(rng.get('end'))
        return here

    def skip(self, node):
        for child in node.get('inner', []):
            self.node(child)
            self.skip(child)


def params(node):
    return [(p.get('name', ''), p['type']['qualType']) for p in node.get('inner', []) if p.get('kind') == 'ParmVarDecl']


def result_type(qual):
    # "int (SSL *, int)" -> "int"; a function returning a function pointer is spelled "void (*(void))(int)".
    depth, i = 0, len(qual) - 1
    if not qual.endswith(')'):
        return None
    while i >= 0:
        depth += {')': 1, '(': -1}.get(qual[i], 0)
        if depth == 0:
            break
        i -= 1
    head = qual[:i].rstrip()
    if head.endswith(')') or '(*' in head:
        return None  # returns a function pointer: spelled by alias only
    return head


def derive_declarations(clang, include):
    names = headers(include)
    tree = ast(clang, include, names)
    prefix = str((include / 'openssl').resolve()) + os.sep
    track = FileTracker()
    found = {'crypto': {}, 'ssl': {}}
    signatures = {}

    def visit(node):
        kind = node.get('kind')
        here = track.node(node)
        if kind == 'LinkageSpecDecl':
            for child in node.get('inner', []):
                visit(child)
            return
        track.skip(node)
        if kind not in DECL_KINDS or node.get('isImplicit'):
            return
        if not here or not str(Path(here).resolve()).startswith(prefix):
            return
        header = Path(here).name
        module = found[module_of(header)]
        name = node.get('name')
        if kind == 'FunctionDecl':
            static = node.get('storageClass') == 'static'
            entry = {'header': header, 'type': node['type'].get('desugaredQualType', node['type']['qualType']), 'params': params(node),
                     'variadic': bool(node.get('variadic')), 'static': static}
            signatures[name] = entry
            module.setdefault('internal' if static else 'functions', {})[name] = header
        elif kind == 'TypedefDecl':
            module.setdefault('types', {})[name] = header
        elif kind in ('RecordDecl', 'CXXRecordDecl'):
            if name:
                module.setdefault('tags', {})[name] = header
        elif kind == 'EnumDecl':
            if name:
                module.setdefault('tags', {})[name] = header
            for item in node.get('inner', []):
                if item.get('kind') == 'EnumConstantDecl':
                    module.setdefault('enumerators', {})[item['name']] = header
        elif kind == 'VarDecl':
            module.setdefault('objects', {})[name] = header

    for node in tree.get('inner', []):
        visit(node)
    # A name is declared once in the module of the first header that declares it.
    seen = set()
    for module in ('crypto', 'ssl'):
        for kind, entries in found[module].items():
            for name in list(entries):
                if (kind, name) in seen:
                    del entries[name]
                seen.add((kind, name))
    return found, signatures


# ── macros, from the preprocessor ────────────────────────────────────────────

MACRO = re.compile(r'#define\s+([A-Za-z_]\w*)(\(([^)]*)\))?\s*(.*)$')


def macros(clang, include):
    source = ''.join(f'#include <openssl/{h}>\n' for h in headers(include))
    command = [clang, '-std=c++23', '-E', '-dD', '-w', '-I', str(include), '-x', 'c++', '-']
    text = subprocess.run(command, check=True, input=source, stdout=subprocess.PIPE, text=True).stdout
    prefix = str((include / 'openssl').resolve()) + os.sep
    current, out = '', {}
    for line in text.splitlines():
        if line.startswith('# ') and '"' in line:
            current = line.split('"')[1]
            continue
        if not current or current.startswith('<') or not str(Path(current).resolve()).startswith(prefix):
            continue
        if line.startswith('#undef '):
            out.pop(line.split()[1], None)
            continue
        match = MACRO.match(line)
        if match:
            name, has_params, plist, body = match.group(1), match.group(2), match.group(3), match.group(4).strip()
            out[name] = {'header': Path(current).name,
                         'params': [p.strip() for p in plist.split(',') if p.strip()] if has_params else None,
                         'body': body}
    return out


def split_args(text):
    depth, start, out = 0, 0, []
    for i, c in enumerate(text):
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif c == ',' and depth == 0:
            out.append(text[start:i].strip())
            start = i + 1
    out.append(text[start:].strip())
    return [] if out == [''] else out


def strip_parens(text):
    text = text.strip()
    while text.startswith('(') and text.endswith(')'):
        depth = 0
        for i, c in enumerate(text):
            depth += {'(': 1, ')': -1}.get(c, 0)
            if depth == 0 and i != len(text) - 1:
                return text
        text = text[1:-1].strip()
    return text


CAST = re.compile(r'^\(\s*(?:const\s+|unsigned\s+|signed\s+|struct\s+|volatile\s+)*[A-Za-z_]\w*(?:\s+\w+)*[\s*]*\)\s*')
CALL = re.compile(r'^(?:(\(\s*[A-Za-z_][\w\s*]*\))\s*)?([A-Za-z_]\w*)\s*\((.*)\)$', re.S)


def textual_reason(name, entry):
    body, plist = entry['body'], entry['params']
    if not body:
        if name.endswith('_H') or name.startswith('HEADER_') or name.endswith('_H_'):
            return 'header guard'
        return 'configuration switch or annotation (empty): test it with #ifdef'
    if plist is not None and '...' in ''.join(plist):
        return 'variadic'
    if '#' in body:
        return 'stringizes or pastes tokens'
    if any(token in body for token in FILE_MACROS):
        return 'records its caller\'s __FILE__/__LINE__'
    if re.search(r'\b(ossl_check_\w+|STACK_OF|LHASH_OF|SKM_\w+|DEFINE_\w+|DECLARE_\w+|IMPLEMENT_\w+|sk_\w+|lh_\w+)\b', body) or \
            re.match(r'(sk_|lh_|SKM_|DEFINE_|DECLARE_|IMPLEMENT_|ossl_check_)', name):
        return 'type-generic (stack/lhash/declaration machinery)'
    if re.search(r'\b(do|while|for|if|return|typedef|struct|extern|static)\b', body):
        return 'statement, declaration or control flow'
    if re.match(r'^__attribute__|^__declspec|^OSSL_DEPRECATED|^ossl_inline|^ossl_noreturn|^ossl_unused', body):
        return 'annotation'
    return None


def call_candidate(name, entry, callables):
    """(return type or None, [(param, type)], callee) when the expansion forwards to one call."""
    plist = entry['params'] or []
    body = strip_parens(entry['body'])
    match = CALL.match(body)
    if not match:
        return None
    cast, callee, inner = match.group(1), match.group(2), match.group(3)
    if callee not in callables or callee == name:
        return None
    callee_params, callee_result, callee_variadic = callables[callee]
    args = split_args(inner)
    if len(args) < len(callee_params) or (len(args) > len(callee_params) and not callee_variadic):
        return None
    typed = {}
    for index, arg in enumerate(args):
        bare = strip_parens(arg)
        cast_away = False
        while True:
            uncast = CAST.sub('', bare, count=1)
            if uncast == bare:
                break
            cast_away = True
            bare = strip_parens(uncast)
        used = [p for p in plist if re.search(r'(?<![\w])' + re.escape(p) + r'(?![\w])', arg)]
        if not used:
            continue
        if bare not in plist or index >= len(callee_params):
            return None
        declared_type = callee_params[index][1]
        # The macro casts the argument to the function's pointer type, so it takes any object pointer, const or not.
        if cast_away and declared_type.rstrip().endswith('*') and '(' not in declared_type:
            declared_type = 'const void *'
        typed.setdefault(bare, declared_type)
    if set(typed) != set(plist):
        return None
    result = strip_parens(cast)[0:] if cast else callee_result
    if cast:
        result = cast.strip()[1:-1].strip()
    if result is None:
        return None
    return result, [(p, typed[p]) for p in plist], callee


def compile_probe(clang, include, lines, extra_headers=''):
    """Line numbers (1-based within `lines`) the compiler rejects, with the first message of each."""
    names = ''.join(f'#include <openssl/{h}>\n' for h in headers(include))
    preamble = names + extra_headers + 'template <class T> using mwrap_t = T;\n'
    offset = preamble.count('\n')
    with tempfile.TemporaryDirectory(prefix='openssl-probe-') as directory:
        source = Path(directory) / 'probe.cpp'
        source.write_text(preamble + '\n'.join(lines) + '\n', encoding='utf-8')
        result = subprocess.run([clang, '-std=c++23', '-fsyntax-only', '-ferror-limit=0', '-Wno-deprecated-declarations',
                                 '-Wno-everything', '-I', str(include), str(source)], stderr=subprocess.PIPE, text=True)
    bad = {}
    for match in re.finditer(r'probe\.cpp:(\d+):\d+: error: (.*)', result.stderr):
        line = int(match.group(1)) - offset
        if 1 <= line <= len(lines):
            bad.setdefault(line, match.group(2))
    return bad


def library_symbols(clang, include):
    """The external symbols libcrypto and libssl define, as compat.openssl built them."""
    nm = Path(clang).with_name('llvm-nm')
    archives = sorted(str(p) for p in (include.parent / 'lib').glob('lib*.a'))
    assert archives, include.parent / 'lib'
    text = subprocess.run([str(nm) if nm.exists() else 'nm', '-g', '--defined-only', *archives], check=True,
                          stdout=subprocess.PIPE, text=True).stdout
    return {parts[-1] for parts in (line.split() for line in text.splitlines()) if len(parts) == 3}


def classify_macros(clang, include, declared, signatures):
    defined = macros(clang, include)
    record = {'constants': {}, 'calls': {}, 'textual': {}}
    callables = {}
    for name, entry in signatures.items():
        result = result_type(entry['type'])
        if result is not None:
            callables[name] = (entry['params'], result, entry['variadic'])
    pending = {}
    for name, entry in defined.items():
        reason = textual_reason(name, entry)
        if reason:
            record['textual'][name] = {'header': entry['header'], 'reason': reason}
        elif entry['params'] is None and re.fullmatch(r'[A-Za-z_]\w*', entry['body']) and (
                entry['body'] in callables or (entry['body'] in defined and defined[entry['body']]['params'] is not None)):
            # an alias of a function, or of a function-like macro: a call with its signature
            pending[name] = dict(entry, params=[], alias=entry['body'])
        elif entry['params'] is None:
            record['constants'][name] = {'header': entry['header']}
        else:
            pending[name] = entry
    # Calls: resolve against functions, then against calls already resolved, until nothing changes.
    calls = {}
    while True:
        progress = False
        for name, entry in list(pending.items()):
            if 'alias' in entry:
                target = entry['alias']
                if target not in callables:
                    continue
                plist, result, variadic = callables[target]
                if variadic:
                    continue
                calls[name] = {'header': entry['header'], 'result': result,
                               'params': [[p or f'a{i}', t] for i, (p, t) in enumerate(plist)], 'alias': target}
            else:
                candidate = call_candidate(name, entry, callables)
                if not candidate:
                    continue
                result, typed, callee = candidate
                calls[name] = {'header': entry['header'], 'result': result, 'params': [list(p) for p in typed], 'callee': callee}
            callables[name] = ([tuple(p) for p in calls[name]['params']], calls[name]['result'], False)
            del pending[name]
            progress = True
        if not progress:
            break
    for name, entry in pending.items():
        record['textual'][name] = {'header': entry['header'], 'reason': 'not one call of a declared function with each parameter passed whole'}
    # The compiler decides the rest: constants must be constant expressions, calls must compile with the derived types.
    names = list(record['constants'])
    while names:
        bad = compile_probe(clang, include, [f'inline constexpr auto mwrap_probe_{i} = {n};' for i, n in enumerate(names)])
        if not bad:
            break
        for line, message in bad.items():
            name = names[line - 1]
            body = defined[name]['body']
            reason = 'a comma-separated list (OID arcs)' if len(split_args(strip_parens(body))) > 1 else 'not a constant expression: ' + message
            record['textual'][name] = {'header': record['constants'].pop(name)['header'], 'reason': reason}
        names = list(record['constants'])
    while calls:
        order = list(calls)
        bad = compile_probe(clang, include, [call_wrapper(f'mwrap_probe_{i}', n, calls[n]) for i, n in enumerate(order)])
        if not bad:
            break
        for line, message in bad.items():
            name = order[line - 1]
            record['textual'][name] = {'header': calls.pop(name)['header'], 'reason': 'does not forward with its function\'s types: ' + message}
    # A call must reach a function the library defines: a header may declare one it only builds elsewhere
    # (ebcdic.h's _openssl_ascii2ebcdic, for EBCDIC hosts).
    defined_symbols = library_symbols(clang, include)
    internal = {n for n, sig in signatures.items() if sig.get('static')}

    def target(name, seen=()):
        call = calls.get(name)
        if call is None:
            return name
        nxt = call.get('callee') or call.get('alias')
        return nxt if nxt in seen else target(nxt, seen + (name,))
    for name in list(calls):
        final = target(name)
        if final not in internal and final not in defined_symbols:
            record['textual'][name] = {'header': calls.pop(name)['header'],
                                       'reason': f'expands to {final}, which the library does not define on this platform'}
    record['calls'] = calls
    # A mapping cannot have the name of a declared entity of the same module scope.
    for kind in ('constants', 'calls'):
        for name in list(record[kind]):
            if any(name in d.get(k, {}) for d in declared.values() for k in d):
                record['textual'][name] = {'header': record[kind].pop(name)['header'], 'reason': 'also the name of a declaration'}
    return {kind: dict(sorted(entries.items())) for kind, entries in record.items()}


def call_wrapper(function, name, call):
    params = ', '.join(f'mwrap_t<{t}> {p}' for p, t in call['params'])
    args = ', '.join(p for p, _ in call['params'])
    invoke = f'{name}({args})' if 'alias' not in call else f'{name}({args})'
    body = f'{invoke};' if call['result'] == 'void' else f'return {invoke};'
    return f'inline mwrap_t<{call["result"]}> {function}({params}) {{ {body} }}'


def derive(clang):
    include = include_dir()
    declared, signatures = derive_declarations(clang, include)
    internal_signatures = {}
    for module_name, module in declared.items():
        for name in module.get('internal', {}):
            sig = signatures[name]
            internal_signatures[name] = {'module': module_name, 'result': result_type(sig['type']),
                                         'params': [[p or f'a{i}', t] for i, (p, t) in enumerate(sig['params'])], 'variadic': sig['variadic']}
    macro_record = classify_macros(clang, include, declared, signatures)
    out = {'openssl': VERSION, 'headers': headers(include)}
    for module in ('crypto', 'ssl'):
        out[module] = {kind: sorted(entries) for kind, entries in sorted(declared[module].items())}
    adapted, skipped = {}, {}
    for name, sig in sorted(internal_signatures.items()):
        if name.startswith('ossl_check_'):
            skipped[name] = 'helper of the type-generic stack/lhash macros'
        elif sig['result'] is None or sig['variadic']:
            skipped[name] = 'returns a function pointer or is variadic'
        else:
            adapted[name] = sig
    out['internal'] = {'adapted': adapted, 'not exported': skipped}
    out['macros'] = macro_record
    return out


def record():
    return json.loads(RECORD.read_text(encoding='utf-8'))


# ── the module sources ───────────────────────────────────────────────────────

BANNER = '// Generated by tools/surface.py from the OpenSSL {v} headers compat.openssl installs\n// (tools/surface.json) — do not edit by hand.\n'


def includes(rec, module=None):
    names = [h for h in rec['headers'] if module is None or module_of(h) == module or module == 'ssl']
    return ''.join(f'#include <openssl/{h}>\n' for h in names)


def declarations_text(rec, module):
    lines = [BANNER.format(v=rec['openssl']), f'// mcpplibs.mwrap.openssl.{module} — the declarations of the {"libssl" if module == "ssl" else "libcrypto"} headers,',
             '// the upstream globals by `using`, unchanged.', 'module;', '#include "detail/prelude.hpp"']
    lines.append(includes(rec, module).rstrip('\n'))
    lines += ['', f'export module mcpplibs.mwrap.openssl.{module};', '',
              '#if defined(__clang__)', '#pragma clang diagnostic ignored "-Wdeprecated-declarations"', '#elif defined(__GNUC__)',
              '#pragma GCC diagnostic ignored "-Wdeprecated-declarations"', '#endif', '']
    entries = rec[module]
    for kind, title in (('types', 'types'), ('tags', 'struct, union and enumeration tags'), ('enumerators', 'enumerators'),
                        ('objects', 'objects'), ('functions', 'functions')):
        names = entries.get(kind, [])
        if names:
            lines.append(f'// {title} ({len(names)})')
            lines += [f'export using ::{name};' for name in names]
            lines.append('')
    adapted = {n: sig for n, sig in rec['internal']['adapted'].items() if sig['module'] == module}
    if adapted:
        lines += ['// The headers\' functions of internal linkage (`static ossl_inline`: every includer has its own, and',
                  f'// none can be exported), declared again under their names, forwarding to them ({len(adapted)}).',
                  'export namespace mcpplibs::mwrap::openssl {']
        for name, sig in adapted.items():
            params = ', '.join(f'mwrap_openssl_t<{t}> {p}' for p, t in sig['params'])
            args = ', '.join(p for p, _ in sig['params'])
            body = f'::{name}({args});' if sig['result'] == 'void' else f'return ::{name}({args});'
            lines.append(f'mwrap_openssl_t<{sig["result"]}> {name}({params}) {{ {body} }}')
        lines.append('}  // namespace mcpplibs::mwrap::openssl')
    return '\n'.join(lines) + '\n'


def capture_text(rec):
    macros_ = rec['macros']
    lines = [BANNER.format(v=rec['openssl']), '// The values and calls of the macros mcpplibs.mwrap.openssl.macros declares, taken while the',
             '// macros are defined (src/macros.cppm includes this in its global module fragment, then undefines them).',
             '#pragma once', '#include "prelude.hpp"', includes(rec).rstrip('\n'), '',
             '#if defined(__clang__)', '#pragma clang diagnostic push', '#pragma clang diagnostic ignored "-Wdeprecated-declarations"',
             '#elif defined(__GNUC__)', '#pragma GCC diagnostic push', '#pragma GCC diagnostic ignored "-Wdeprecated-declarations"', '#endif', '',
             'namespace mwrap_openssl_capture {', 'template <class T> using mwrap_t = T;']
    lines += [line for n in macros_['constants'] for line in guarded(n, f'inline constexpr auto value_{n} = {n};')]
    lines += [call_wrapper(f'call_{n}', n, c) for n, c in macros_['calls'].items()]
    lines += ['}  // namespace mwrap_openssl_capture', '', '#if defined(__clang__)', '#pragma clang diagnostic pop', '#elif defined(__GNUC__)',
              '#pragma GCC diagnostic pop', '#endif']
    return '\n'.join(lines) + '\n'


def macros_text(rec):
    macros_ = rec['macros']
    lines = [BANNER.format(v=rec['openssl']),
             '// mcpplibs.mwrap.openssl.macros — OpenSSL\'s macros (a named module cannot export a macro), under their',
             '// original names in mcpplibs::mwrap::openssl::macros: the constants as `inline constexpr` of the',
             '// expansion\'s type; the macros that expand to one call of a function as functions with that function\'s',
             '// parameter and return types. The other macros stay macros: <mwrap/openssl/macros.hpp> (docs/usage.md).',
             'module;', '#include "detail/capture.hpp"', '']
    names = list(macros_['constants']) + list(macros_['calls'])
    lines += [f'#undef {n}' for n in names]
    lines += ['', 'export module mcpplibs.mwrap.openssl.macros;', '',
              '#if defined(__clang__)', '#pragma clang diagnostic ignored "-Wdeprecated-declarations"', '#elif defined(__GNUC__)',
              '#pragma GCC diagnostic ignored "-Wdeprecated-declarations"', '#endif', '',
              'export namespace mcpplibs::mwrap::openssl::macros {', f'// constants ({len(macros_["constants"])})']
    lines += [line for n in macros_['constants'] for line in guarded(n, f'inline constexpr auto {n} = mwrap_openssl_capture::value_{n};')]
    lines.append(f'// calls ({len(macros_["calls"])})')
    for name, call in macros_['calls'].items():
        params = ', '.join(f'mwrap_openssl_t<{t}> {p}' for p, t in call['params'])
        args = ', '.join(p for p, _ in call['params'])
        target = f'mwrap_openssl_capture::call_{name}({args})'
        body = f'{target};' if call['result'] == 'void' else f'return {target};'
        lines.append(f'mwrap_openssl_t<{call["result"]}> {name}({params}) {{ {body} }}')
    lines.append('}  // namespace mcpplibs::mwrap::openssl::macros')
    return '\n'.join(lines) + '\n'


