def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clang', help='derive tools/surface.json with this clang++')
    parser.add_argument('--write', action='store_true', help='write the module sources from the record')
    args = parser.parse_args()
    if args.clang:
        RECORD.write_text(json.dumps(derive(args.clang), indent=1) + '\n', encoding='utf-8')
    rec = record()
    if args.write:
        for path, render in OUTPUTS.items():
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            text = render(rec)
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                target.write_text(text, encoding='utf-8')
    for module in ('crypto', 'ssl'):
        print(module + ': ' + ', '.join(f'{len(v)} {k}' for k, v in rec[module].items()))
    print('internal: ' + ', '.join(f'{len(v)} {k}' for k, v in rec['internal'].items()))
    print('macros: ' + ', '.join(f'{len(v)} {k}' for k, v in rec['macros'].items()))


if __name__ == '__main__':
    main()
