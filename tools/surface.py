def macros_doc_text(rec):
    macros_ = rec['macros']
    lines = ['# OpenSSL\'s macros in openssl-m', '',
             f'Generated by `tools/surface.py` from the OpenSSL {rec["openssl"]} headers (the record: `tools/surface.json`). '
             'Every macro the public headers define is in one class:', '',
             f'- **{len(macros_["constants"])} constants**: `inline constexpr` in `mcpplibs::mwrap::openssl::macros`, of the expansion\'s type '
             '(each compared with its macro by `tests/constants_test.cpp`; the names are in `tools/surface.json`).',
             f'- **{len(macros_["calls"])} calls**: functions of the same name in `mcpplibs::mwrap::openssl::macros`, listed below.',
             f'- **{len(macros_["textual"])} textual**: macros only, from `<mwrap/openssl/macros.hpp>`; listed below with the reason.', '',
             '## Calls', '',
             'Each expands to one call of the function shown, with every parameter passed whole; the mapping takes that function\'s '
             'parameter types (`const void *` where the macro casts a pointer argument) and returns its result. It evaluates each '
             'argument once.', '', '| Macro | Calls |', '|---|---|']
    for name, call in macros_['calls'].items():
        params = ', '.join(t for _, t in call['params'])
        lines.append(f'| `{name}({params})` | `{call.get("callee") or call.get("alias")}` |')
    lines += ['', '## Textual', '']
    groups = {}
    for name, entry in macros_['textual'].items():
        groups.setdefault(entry['reason'], []).append(name)
    for reason, names in sorted(groups.items(), key=lambda item: (-len(item[1]), item[0])):
        lines += [f'### {reason} ({len(names)})', '', ', '.join(f'`{n}`' for n in names), '']
    return '\n'.join(lines).rstrip('\n') + '\n'


